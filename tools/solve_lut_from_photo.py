#!/usr/bin/env python3
"""Solve CP1025 CIE L* CMYK LUT from a photographed Macro-Stripe Self-Calibration Target."""
import argparse
import json
import os
import numpy as np
from PIL import Image, ImageOps
from scipy.signal import fftconvolve
from scipy.ndimage import map_coordinates, gaussian_filter1d


def find_bullseye(g, w_im, x0, y0, x1, y1):
    h_im = g.shape[0]
    sub = g[y0:y1, x0:x1]
    r_outer = max(8, int(round(w_im * 0.0235 / 2)))
    r_inner = max(4, int(round(r_outer * 36 / 60)))
    r_core = max(2, int(round(r_outer * 16 / 60)))
    sz = 2 * r_outer + 5
    tmpl = np.ones((sz, sz), dtype=np.float64)
    c = sz // 2
    tmpl[c - r_outer : c + r_outer + 1, c - r_outer : c + r_outer + 1] = -1.0
    tmpl[c - r_inner : c + r_inner + 1, c - r_inner : c + r_inner + 1] = 1.0
    tmpl[c - r_core : c + r_core + 1, c - r_core : c + r_core + 1] = -1.0
    tmpl -= tmpl.mean()
    resp = fftconvolve(sub - sub.mean(), tmpl[::-1, ::-1], mode="valid")
    idx = np.unravel_index(np.argmax(resp), resp.shape)
    by, bx = y0 + idx[0] + c, x0 + idx[1] + c
    pad = r_outer + 6
    py0, py1 = max(0, by - pad), min(h_im, by + pad + 1)
    px0, px1 = max(0, bx - pad), min(w_im, bx + pad + 1)
    patch = g[py0:py1, px0:px1]
    p_th = np.percentile(patch, 5) + 0.45 * (np.percentile(patch, 95) - np.percentile(patch, 5))
    pm = (patch < p_th).astype(np.float64)
    yy, xx = np.mgrid[0 : pm.shape[0], 0 : pm.shape[1]]
    return px0 + (xx * pm).sum() / pm.sum(), py0 + (yy * pm).sum() / pm.sum()


def pava_increasing(y):
    blocks = [[float(val), 1] for val in y]
    i = 0
    while i < len(blocks) - 1:
        if blocks[i][0] > blocks[i + 1][0]:
            tot_w = blocks[i][1] + blocks[i + 1][1]
            avg = (blocks[i][0] * blocks[i][1] + blocks[i + 1][0] * blocks[i + 1][1]) / tot_w
            blocks[i] = [avg, tot_w]
            blocks.pop(i + 1)
            if i > 0:
                i -= 1
        else:
            i += 1
    out = []
    for val, w in blocks:
        out.extend([val] * w)
    return np.array(out, dtype=np.float64)


def target_lstar(t, r_s=0.14):
    l_s = 116.0 * (r_s ** (1.0 / 3.0)) - 16.0
    l_t = 100.0 * (1.0 - t) + l_s * t
    r_t = ((l_t + 16.0) / 116.0) ** 3
    return (1.0 - r_t) / (1.0 - r_s)


def main():
    parser = argparse.ArgumentParser(
        description="Solve CP1025 CIE L* CMYK LUT from a photographed Macro-Stripe Self-Calibration Target."
    )
    parser.add_argument("--photo", required=True, help="Path to photographed calibration sheet (JPEG/PNG).")
    parser.add_argument("--layout", required=True, help="Path to layout JSON generated by gen_calib_target.py.")
    parser.add_argument(
        "--mode",
        choices=("pwm2", "1x1"),
        default=None,
        help="LUT mode (defaults to layout['mode'], or 'pwm2' if omitted).",
    )
    parser.add_argument(
        "--rs",
        type=float,
        default=0.14,
        help="Solid-toner reflectance parameter r_s for CIE L* target curve. Default: 0.14",
    )
    parser.add_argument("--out-lut", default=None, help="Output .dat LUT path.")
    parser.add_argument("--out-header", default=None, help="Output C header (.h) path.")
    args = parser.parse_args()

    with open(args.layout) as f:
        layout = json.load(f)

    mode = args.mode or layout.get("mode", "pwm2")
    out_lut = args.out_lut or (
        "crd/zjs/lut_cmyk_pwm2.dat" if mode == "pwm2" else "crd/zjs/lut_cmyk_1x1.dat"
    )
    out_header = args.out_header or (
        "embedded_lut_pwm2.h" if mode == "pwm2" else "embedded_lut.h"
    )

    img = ImageOps.exif_transpose(Image.open(args.photo)).convert("RGB")
    arr = np.array(img, dtype=np.float64)
    h_im, w_im, _ = arr.shape
    gray = 0.299 * arr[:, :, 0] + 0.587 * arr[:, :, 1] + 0.114 * arr[:, :, 2]

    boxes = [
        (int(w_im * 0.01), int(h_im * 0.01), int(w_im * 0.22), int(h_im * 0.22)),
        (int(w_im * 0.78), int(h_im * 0.01), int(w_im * 0.99), int(h_im * 0.22)),
        (int(w_im * 0.01), int(h_im * 0.78), int(w_im * 0.22), int(h_im * 0.99)),
        (int(w_im * 0.78), int(h_im * 0.78), int(w_im * 0.99), int(h_im * 0.99)),
    ]
    src_pts = [find_bullseye(gray, w_im, *b) for b in boxes]
    dst_pts = [(f["cx"], f["cy"]) for f in layout["fiducials"]]

    a_mat = []
    for (sx, sy), (dx, dy) in zip(src_pts, dst_pts):
        a_mat.append([dx, dy, 1, 0, 0, 0, -sx * dx, -sx * dy, -sx])
        a_mat.append([0, 0, 0, dx, dy, 1, -sy * dx, -sy * dy, -sy])
    _, _, vt = np.linalg.svd(np.array(a_mat, dtype=np.float64))
    h_mat = vt[-1].reshape(3, 3)
    h_mat /= h_mat[2, 2]

    max_err = 0.0
    for (sx, sy), (dx, dy) in zip(src_pts, dst_pts):
        p = h_mat @ np.array([dx, dy, 1.0])
        p /= p[2]
        err = float(np.hypot(p[0] - sx, p[1] - sy))
        max_err = max(max_err, err)
    assert max_err < 1.0, f"Homography error too high: {max_err:.4f} px"
    print(f"Homography max reprojection error: {max_err:.4f} px")

    scale = 4
    cw, ch_px = layout["width"] // scale, layout["height"] // scale
    yy, xx = np.mgrid[0:ch_px, 0:cw]
    px, py = xx * scale, yy * scale
    den = h_mat[2, 0] * px + h_mat[2, 1] * py + h_mat[2, 2]
    u = (h_mat[0, 0] * px + h_mat[0, 1] * py + h_mat[0, 2]) / den
    v = (h_mat[1, 0] * px + h_mat[1, 1] * py + h_mat[1, 2]) / den
    warped = np.stack([map_coordinates(arr[:, :, c], [v, u], order=1, mode="nearest") for c in range(3)], axis=2)

    s = np.clip(warped / 255.0, 0.0, 1.0)
    lin = np.where(s <= 0.04045, s / 12.92, ((s + 0.055) / 1.055) ** 2.4)

    gap_ys = [(395, 430), (1715, 1775), (3065, 3125), (4415, 4475), (5765, 5825)]
    gap_profs = [
        np.stack([gaussian_filter1d(lin[y0 // scale : y1 // scale, :, c].mean(axis=0), sigma=30) for c in range(3)], axis=1)
        for y0, y1 in gap_ys
    ]
    gap_y_mid = [0.5 * (y0 + y1) for y0, y1 in gap_ys]

    def sample_local_flat(ci, ch_name, p, margin_x=28, margin_y=40):
        y0_p, y1_p = p["y0"] + margin_y, p["y1"] - margin_y
        x0_p, x1_p = p["x0"] + margin_x, p["x1"] - margin_x
        ym = 0.5 * (y0_p + y1_p)
        t = (ym - gap_y_mid[ci]) / (gap_y_mid[ci + 1] - gap_y_mid[ci])
        w_prof = (1.0 - t) * gap_profs[ci] + t * gap_profs[ci + 1]
        norm = lin[y0_p // scale : y1_p // scale, x0_p // scale : x1_p // scale, :] / np.maximum(
            w_prof[x0_p // scale : x1_p // scale, :][None, :, :], 1e-6
        )
        if ch_name == "C":
            return float(norm[:, :, 0].mean())
        if ch_name == "M":
            return float(norm[:, :, 1].mean())
        if ch_name == "Y":
            return float(norm[:, :, 2].mean())
        return float((0.299 * norm[:, :, 0] + 0.587 * norm[:, :, 1] + 0.114 * norm[:, :, 2]).mean())

    a_grid = np.array(layout["ref_a_pct"], dtype=np.float64) / 100.0
    raw_v = np.array(layout["raw_v"], dtype=np.float64)

    t_all = np.linspace(0.0, 1.0, 256)
    a_tgt = target_lstar(t_all, r_s=args.rs)

    lut_out = np.zeros((256, 4), dtype=int)
    measured_curves = {}

    for ci, ch_name in enumerate(["C", "M", "Y", "K"]):
        info = layout["channels"][ch_name]
        ra = np.array([sample_local_flat(ci, ch_name, p) for p in info["row_a"]])
        rb = np.array([sample_local_flat(ci, ch_name, p) for p in info["row_b"]])

        rb_adj = rb + (ra[0] - rb[0]) * (1.0 - raw_v / 255.0)
        r_ref_a = np.minimum.accumulate(ra)
        r_min = min(float(ra[-1]), float(np.min(rb_adj)))
        frac_a100 = (ra[0] - ra[-1]) / max(ra[0] - r_min, 1e-6)
        if abs(r_min - ra[-1]) < 1e-6:
            a_ref_ext = a_grid.copy()
            r_ref_ext = r_ref_a.copy()
        else:
            a_ref_ext = np.append(a_grid * frac_a100, 1.0)
            r_ref_ext = np.append(r_ref_a, r_min)

        a_full = np.interp(rb_adj, r_ref_ext[::-1], a_ref_ext[::-1])
        assert a_full.max() >= 0.95, f"{ch_name} peak coverage too low: {a_full.max():.3f}"

        i_peak = int(np.argmax(a_full))
        v_sub = raw_v[: i_peak + 1]
        a_sub = pava_increasing(a_full[: i_peak + 1])
        a_sub[0] = 0.0
        a_sub[-1] = 1.0
        a_strict = a_sub + 1e-4 * (v_sub / 255.0)
        a_strict[0] = 0.0
        a_strict /= a_strict[-1]

        v_inv = np.interp(a_tgt, a_strict, v_sub)
        v_sm = gaussian_filter1d(v_inv, sigma=2.0, mode="nearest")
        v_lut = np.clip(np.round(v_sm), 0, 255).astype(int)
        v_lut[0] = 0

        v_start_tail = v_lut[242]
        for ii in range(243, 256):
            frac = (ii - 242) / (255.0 - 242.0)
            v_lut[ii] = int(round(v_start_tail + (255 - v_start_tail) * (frac ** 1.5)))
        v_lut[255] = 255

        for ii in range(1, 256):
            if v_lut[ii] < v_lut[ii - 1]:
                v_lut[ii] = v_lut[ii - 1]
        assert v_lut[0] == 0 and v_lut[255] == 255

        lut_out[:, ci] = v_lut
        measured_curves[ch_name] = (v_sub, a_sub)

    lut_dir = os.path.dirname(out_lut)
    if lut_dir:
        os.makedirs(lut_dir, exist_ok=True)
    np.savetxt(out_lut, lut_out, fmt="%d", delimiter=" ")

    hdr_dir = os.path.dirname(out_header)
    if hdr_dir:
        os.makedirs(hdr_dir, exist_ok=True)
    names = ["Cyan", "Magenta", "Yellow", "Black"]
    if mode == "pwm2":
        hdr_comment = f"/* Calibrated 1200x600 3-Level PWM CMYK LUT (Macro-Stripe CIE L* Self-Calibrated, r_s={args.rs:g}) */\n"
        sym_name = "default_calibrated_lut_pwm2"
    else:
        hdr_comment = f"/* Calibrated 1x1 CMYK LUT (Macro-Stripe CIE L* Self-Calibrated, r_s={args.rs:g}) */\n"
        sym_name = "default_calibrated_lut"

    with open(out_header, "w") as f:
        f.write(hdr_comment)
        f.write(f"static const unsigned char {sym_name}[4][256] = {{\n")
        for c in range(4):
            f.write(f"    /* Channel {c}: {names[c]} */\n")
            f.write("    {\n")
            for row_idx in range(16):
                vals = ", ".join(f"{int(lut_out[row_idx * 16 + j, c]):3d}" for j in range(16))
                f.write(f"        {vals},\n")
            f.write("    },\n")
        f.write("};\n")

    steps = [0, 5, 10, 15, 20, 25, 30, 35, 40, 50, 60, 70, 80, 90, 95, 100]
    print(f"\n=== Solved CIE L* LUT ({mode}, r_s={args.rs:g}) & Predicted Physical Coverage a_eff(%) ===")
    print(f"{'Step':>4s} {'Tgt%':>5s} | {'C: v->a%':>10s} | {'M: v->a%':>10s} | {'Y: v->a%':>10s} | {'K: v->a%':>10s}")
    for s_pct in steps:
        idx = int(round(s_pct * 255 / 100))
        tgt = a_tgt[idx] * 100.0
        parts = [f"{s_pct:3d}% {tgt:5.1f}"]
        for ci, ch_name in enumerate(["C", "M", "Y", "K"]):
            v_val = int(lut_out[idx, ci])
            v_sub, a_sub = measured_curves[ch_name]
            a_pred = float(np.interp(v_val, v_sub, a_sub)) * 100.0 if v_val <= v_sub[-1] else 100.0
            parts.append(f"{v_val:3d}->{a_pred:4.1f}%")
        print(" | ".join(parts))

    print(f"\nSaved {out_lut} and regenerated {out_header}")


if __name__ == "__main__":
    main()
